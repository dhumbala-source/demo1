package com.rainbow.demo;

public class Employee {
    private Integer id;
    
    public Integer getId() {
        return id;
    }
    public void setId(Integer id) {
        this.id = id;
    }
    private String name;
   
    public void setName(String name) {
        this.name = name;
    }
    public String getName() {
        return name;
    }
    private String role;

    public void setRole(String role) {
        this.role = role;
    }
    public String getRole() {
        return role;
    }
    

    
}
